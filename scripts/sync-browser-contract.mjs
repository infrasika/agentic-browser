import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const checkout = resolve(process.argv[2] ?? resolve(root, '../librechat-agent'));
const target = resolve(checkout, 'packages/data-provider/src/browser');
const require = createRequire(resolve(checkout, 'package.json'));
const prettier = require('prettier');
await mkdir(target, { recursive: true });
for (const name of ['actions', 'protocol']) {
  const source = await readFile(resolve(root, `src/api/${name}.ts`), 'utf8');
  const sha = createHash('sha256').update(source).digest('hex');
  const path = resolve(target, `${name}.ts`);
  const format = (await prettier.resolveConfig(path)) ?? {};
  // Match LibreChat's commit/build formatting so --check remains stable after its hooks run.
  const content = await prettier.format(
    `// Generated by agentic-browser/scripts/sync-browser-contract.mjs; source SHA256 ${sha}.\n${source.replaceAll("'./actions.js'", "'./actions'")}`,
    { ...format, filepath: path, plugins: (format.plugins ?? []).map(plugin => typeof plugin === 'string' ? require.resolve(plugin) : plugin) },
  );
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Browser contract differs: ${name}`);
  } else await writeFile(path, content);
}
console.log(process.argv.includes('--check') ? 'Browser protocol matches the LibreChat checkout.' : 'Browser protocol synchronized and versioned in the LibreChat checkout.');
