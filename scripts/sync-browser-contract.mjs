import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(process.argv[2] ?? resolve(root, '../librechat-agent'), 'packages/data-provider/src/browser');
await mkdir(target, { recursive: true });
for (const name of ['actions', 'protocol']) {
  const source = await readFile(resolve(root, `src/api/${name}.ts`), 'utf8');
  const sha = createHash('sha256').update(source).digest('hex');
  const content = `// Generated by agentic-browser/scripts/sync-browser-contract.mjs; source SHA256 ${sha}.\n${source.replaceAll("'./actions.js'", "'./actions'")}`;
  const path = resolve(target, `${name}.ts`);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Browser contract differs: ${name}`);
  } else await writeFile(path, content);
}
console.log('Browser protocol synchronized and versioned in the LibreChat checkout.');
