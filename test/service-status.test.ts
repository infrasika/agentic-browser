import test from 'node:test';
import assert from 'node:assert/strict';
import { createStatusReader } from '../src/service-status.js';
import { fakeWorkspace } from './helpers.js';
import { SessionRegistry } from '../src/sessions.js';
import { IdentityStore } from '../src/identity.js';
import { createHttpServer } from '../src/http.js';
import { once } from 'node:events';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const config = { browserMode: 'docker' as const, runtimePlatform: 'linux/amd64' as const, runtimeImage: 'fixture', dataDirectory: '/private-fixture' };
test('status probes coalesce, report low storage, and never expose raw Docker errors', async () => {
  let calls = 0;
  const ready = createStatusReader(config, { run: async args => { calls++; return args[0] === 'version' ? '29.3' : 'linux/amd64 node'; }, freeMiB: async () => 500 });
  const [a, b] = await Promise.all([ready(), ready()]);
  assert.equal(calls, 2); assert.deepEqual(a, b);
  assert.equal(a.runtime.state, 'ready'); assert.equal(a.storage.state, 'low');
  const fail = createStatusReader(config, { run: async () => { throw new Error('PRIVATE-SECRET-/private/volume'); }, freeMiB: async () => { throw new Error('PRIVATE-SECRET'); } });
  const status = await fail();
  assert.equal(status.docker.state, 'unavailable'); assert.equal(status.runtime.state, 'not_checked');
  assert.equal(status.storage.state, 'unavailable'); assert.ok(!JSON.stringify(status).includes('PRIVATE-SECRET'));
  const wrongArch = createStatusReader(config, { run: async () => 'linux/arm64 node', freeMiB: async () => 2048 });
  assert.equal((await wrongArch()).runtime.state, 'unavailable');
});

test('workspace diagnostics require human authorization; public version exposes no private state', async t => {
  const root = await mkdtemp(join(tmpdir(), 'ab-status-'));
  const identity = new IdentityStore(root);
  await identity.createMember('owner', 'synthetic-status-password');
  const login = await identity.login('owner', 'synthetic-status-password', 'fixture');
  const principal = identity.authenticate(login.token, 'human');
  const key = identity.issueAgent(principal, 'fixture');
  let probes = 0;
  const registry = new SessionRegistry({ create: async () => fakeWorkspace(), close: async () => {} }, { ttlMs: 60000, maxSessions: 3 });
  const reader = createStatusReader(config, { run: async () => { probes++; return 'linux/amd64 node'; }, freeMiB: async () => 2048 });
  const options = { publicUrl: 'http://127.0.0.1', identity, statusReader: reader };
  const server = createHttpServer(registry, options);
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${(server.address() as {port:number}).port}`;
  t.after(async () => { await server.closeRemoteMcp(); server.close(); server.closeAllConnections(); await registry.close(); identity.close(); await rm(root, { recursive: true, force: true }); });
  const version = await (await fetch(base + '/api/version')).json();
  assert.deepEqual(Object.keys(version).sort(), ['revision', 'version']);
  assert.equal((await fetch(base + '/api/service-status')).status, 401);
  assert.equal((await fetch(base + '/api/service-status', { headers: { Authorization: `Bearer ${key.token}` } })).status, 403);
  assert.equal(probes, 0, 'Unauthorized callers never trigger daemon probes');
  const response = await fetch(base + '/api/service-status', { headers: { Cookie: `ab_login=${login.token}` } });
  assert.equal(response.status, 200);
  const data = await response.json(); assert.equal(data.capacity.maxSessions, 3); assert.equal(data.ownSessions, 0);
  assert.ok(!JSON.stringify(data).includes(login.token)); assert.ok(!JSON.stringify(data).includes(key.token));
  identity.revokeAgent(principal, key.id);
});
