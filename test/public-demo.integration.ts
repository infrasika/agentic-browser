import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { chromium } from 'playwright';
import { IdentityStore } from '../src/identity.js';
import { DockerEngine } from '../src/docker-runtime.js';
import { SessionRegistry } from '../src/sessions.js';
import { createHttpServer } from '../src/http.js';

test('public demo: two private offline containers; human login; fixed Agent completion; explicit cleanup', { timeout: 90000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), 'agentic-demo-browser-'));
  const identity = new IdentityStore(join(root, 'identity'));
  const engine = new DockerEngine({ dataDirectory: root, network: 'none', image: process.env.AB_RUNTIME_IMAGE });
  const registry = new SessionRegistry(engine, { ttlMs: 300000, maxSessions: 2, maxSessionsPerOwner: 1, maxLifetimeMs: 600000 });
  const server = createHttpServer(registry, { publicUrl: 'http://127.0.0.1:3333', identity, demo: true });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); await registry.close(); server.close(); server.closeAllConnections(); identity.close(); await rm(root, { recursive: true, force: true }); });
  const a = await browser.newContext(), b = await browser.newContext();
  const page = await a.newPage(); await page.goto(base); await page.locator('#start-demo').click();
  await page.waitForURL('**/view*');
  await page.waitForFunction(() => document.getElementById('connection')?.textContent === 'Connected' && !!document.querySelector('#desktop canvas'));
  const aId = await page.evaluate(() => sessionStorage.getItem('team-viewer-id'));
  const second = await b.newPage(); await second.goto(base); await second.locator('#start-demo').click();
  await second.waitForURL('**/view*');
  await second.waitForFunction(() => document.getElementById('connection')?.textContent === 'Connected' && !!document.querySelector('#desktop canvas'));
  const bId = await second.evaluate(() => sessionStorage.getItem('team-viewer-id')); assert.notEqual(aId, bId);
  assert.equal((await b.request.get(`${base}/api/human/${aId}`)).status(), 404);
  await page.locator('#text').fill('demo-visitor-fixture'); await page.locator('#send-text').click();
  await page.locator('#desktop canvas').focus(); await page.keyboard.press('Tab'); await page.keyboard.type('fictional-demo-password'); await page.keyboard.press('Enter');
  await new Promise(resolve => setTimeout(resolve, 600));
  await page.locator('#resume').click();
  await page.waitForFunction(() => document.getElementById('reason')?.textContent?.includes('Demo complete'));
  await page.waitForFunction(() => document.getElementById('connection')?.textContent === 'Connected' && !!document.querySelector('#desktop canvas'));
  assert.equal((await readdir(join(root, 'runtimes'))).filter(file => file.endsWith('.json')).length, 2);
  await page.locator('#end-session').click(); await page.locator('#recover').waitFor({ state: 'visible' });
  await second.locator('#end-session').click(); await second.locator('#recover').waitFor({ state: 'visible' });
  assert.equal((await readdir(join(root, 'runtimes'))).filter(file => file.endsWith('.json')).length, 0);
  assert.deepEqual(await engine.profiles.list(), []);
});
