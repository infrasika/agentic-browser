test('wait: revision fence, timeout and cancellation never change control or extend the session', async () => {
  const session = new BrowserSession('Wait fixture', fakeWorkspace(), 60000);
  await session.transfer('human'); const before = session.info();
  assert.equal((await waitForSession(session, { control: 'human', afterRevision: before.revision, timeoutMs: 20, signal: new AbortController().signal }, () => {})).status, 'timed_out');
  const cancel = new AbortController();
  const waiting = waitForSession(session, { control: 'agent', timeoutMs: 25000, signal: cancel.signal }, () => {});
  const rejected = assert.rejects(waiting); cancel.abort(); await rejected;
  assert.equal(session.expiresAt, Date.parse(before.expiresAt)); assert.equal(session.info().revision, before.revision);
  const next = waitForSession(session, { control: 'agent', afterRevision: before.revision, timeoutMs: 1000, signal: new AbortController().signal }, () => {});
  await session.transfer('agent'); assert.equal((await next).status, 'ready');
  await session.close();
});

test('HTTP wait: disconnect frees capacity; credential revocation and rebinding interrupt pending waits', async t => {
  const root = await mkdtemp(join(tmpdir(), 'agentic-wait-'));
  const identity = new IdentityStore(root);
  const member = await identity.createMember('alice', 'synthetic-wait-password');
  const login = await identity.login('alice', 'synthetic-wait-password', 'fixture');
  const human = identity.authenticate(login.token, 'human');
  const key = identity.issueAgent(human, 'Wait client');
  const registry = new SessionRegistry({ async create() { return fakeWorkspace(); }, async close() {} }, { ttlMs: 60000, maxSessions: 4 });
  const server = createHttpServer(registry, { publicUrl: 'http://127.0.0.1:3333', identity });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  t.after(async () => { server.close(); server.closeAllConnections(); await registry.close(); identity.close(); await rm(root, { recursive: true, force: true }); });
  const session = await registry.create('HTTP wait', undefined, member.id, identity.authenticate(key.token, 'agent').credentialHash);
  await session.transfer('human');
  const wait = (token: string, signal?: AbortSignal) => fetch(`${base}/api/sessions/${session.id}/wait`, { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ timeoutMs: 25000 }), signal });
  const cancelA = new AbortController(), cancelB = new AbortController();
  const first = wait(key.token, cancelA.signal), second = wait(key.token, cancelB.signal);
  const firstCancelled = assert.rejects(first), secondCancelled = assert.rejects(second);
  await delay(100); assert.equal((await wait(key.token)).status, 429);
  cancelA.abort(); cancelB.abort(); await firstCancelled; await secondCancelled;
  await delay(100);
  const revokedWait = wait(key.token);
  await delay(100); identity.revokeAgent(human, key.id);
  assert.equal((await revokedWait).status, 401);
  assert.equal(session.info().control, 'human');
  const replacement = identity.issueAgent(human, 'Replacement');
  session.agentCredentialHash = identity.authenticate(replacement.token, 'agent').credentialHash;
  const oldBindingWait = wait(replacement.token);
  await delay(100); session.agentCredentialHash = 'different-binding';
  assert.equal((await oldBindingWait).status, 404);
  assert.equal(session.info().control, 'human');
});
