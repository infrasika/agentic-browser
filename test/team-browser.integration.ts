import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { chromium } from 'playwright';
import { IdentityStore } from '../src/identity.js';
import { ChromiumEngine } from '../src/browser.js';
import { SessionRegistry } from '../src/sessions.js';
import { createHttpServer } from '../src/http.js';

test('team browser: login UI, private credentials, human handoff and second-member denial', { timeout: 60000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), 'agentic-team-browser-'));
  const identity = new IdentityStore(root);
  const password = 'synthetic-browser-password';
  await identity.createMember('alice', password); await identity.createMember('bob', password);
  const registry = new SessionRegistry(new ChromiumEngine({ headless: true }), { ttlMs: 60000, maxSessions: 4 });
  const server = createHttpServer(registry, { publicUrl: 'http://127.0.0.1:3333', identity });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); server.close(); server.closeAllConnections(); await registry.close(); identity.close(); await rm(root, { recursive: true, force: true }); });
  const a = await browser.newContext(), b = await browser.newContext();
  const page = await a.newPage();
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.waitForURL('**/login?next=*');
  await page.locator('#username').fill('alice'); await page.locator('#password').fill(password);
  await page.locator('#submit').click(); await page.waitForURL(base + '/');
  await page.locator('#member-name').filter({ hasText: 'alice' }).waitFor();
  assert.equal(await page.locator('#legacy-auth').isVisible(), false);
  await page.locator('summary').click();
  await page.locator('#credential-name').fill('Synthetic client');
  await page.locator('#credential-form button').click();
  await page.locator('#credential-secret').waitFor({ state: 'visible' });
  const token = await page.locator('#credential-secret').inputValue();
  assert.match(token, /^ab_agent_/);
  const agent = async (path: string, method = 'GET', body?: unknown) => {
    const response = await fetch(base + path, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: await response.json() };
  };
  const created = await agent('/api/sessions', 'POST', { purpose: 'Synthetic team acceptance', url: base + '/demo' });
  assert.equal(created.status, 201);
  await page.goto(created.data.humanUrl);
  await page.locator('#takeover').click();
  await page.locator('#resume').waitFor({ state: 'visible' });
  assert.equal((await agent(`/api/sessions/${created.data.id}/actions`, 'POST', { type: 'snapshot' })).status, 409);
  // Real browser UI must send the same-origin cookie, never an Agent key.
  assert.equal((await a.cookies()).find(cookie => cookie.name === 'ab_login')?.httpOnly, true);
  assert.equal(await page.evaluate(() => document.cookie.includes('ab_login=')), false);
  const bob = await b.newPage();
  await bob.goto(created.data.humanUrl);
  await bob.waitForURL('**/login?next=*');
  await bob.locator('#username').fill('bob'); await bob.locator('#password').fill(password);
  await bob.locator('#submit').click();
  await bob.locator('#recover').waitFor({ state: 'visible' });
  assert.equal(await bob.locator('#screen').isVisible(), false);
  await page.locator('#resume').click();
  await page.locator('#takeover').waitFor({ state: 'visible' });
  const snapshot = await agent(`/api/sessions/${created.data.id}/actions`, 'POST', { type: 'snapshot' });
  assert.equal(snapshot.status, 200); assert.match(snapshot.data.result.text, /Demo username/);
  await page.goto(base);
  await page.locator('#member-name').filter({ hasText: 'alice' }).waitFor();
  await mkdir('output/playwright', { recursive: true });
  await page.screenshot({ path: 'output/playwright/team-dashboard.png', fullPage: true });
  await page.locator('#logout').click(); await page.waitForURL(base + '/login');
  assert.equal((await a.request.get(base + '/api/auth/me')).status(), 401);
  assert.deepEqual(errors.filter(error => error !== 'Please sign in first.'), []);
});
